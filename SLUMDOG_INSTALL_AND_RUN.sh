#!/usr/bin/env bash
set -euo pipefail

TARGET_DATE="${TARGET_DATE:-2026-08-22}"
EXPECTED_BASE_TREE="74548d4999a6340b6c5228bd642a86824535d9ea"
EXPECTED_TARGET_TREE="b24d929144e2f3eb92503b3ae15d093c7520e207"
EXPECTED_PATCH_SHA="015dab85d500499de7c647e71747faefb575dd4d514f2242f00491c13a31e7f7"

ROOT="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [[ -z "$ROOT" ]]; then
  echo "ERROR: run this inside the Slumdog Codespace repository."
  exit 2
fi
cd "$ROOT"

REMOTE_URL="$(git remote get-url origin 2>/dev/null || true)"
if [[ "$REMOTE_URL" != *"6ixtyn9-sudo/Slumdog"* ]]; then
  echo "ERROR: origin is not 6ixtyn9-sudo/Slumdog: $REMOTE_URL"
  exit 2
fi

# Permit only the uploaded installer/old patch as untracked transfer files.
DIRTY="$(git status --porcelain | grep -Ev '^\?\? (SLUMDOG_INSTALL_AND_RUN\.sh|SLUMDOG_.*\.patch)$' || true)"
if [[ -n "$DIRTY" ]]; then
  echo "ERROR: repository has unrelated local changes; refusing to overwrite:"
  echo "$DIRTY"
  exit 3
fi

git fetch origin main
git switch main
git pull --ff-only origin main

CURRENT_TREE="$(git rev-parse HEAD^{tree})"
if [[ "$CURRENT_TREE" == "$EXPECTED_TARGET_TREE" ]]; then
  echo "Full-build tree is already installed; skipping patch application."
elif [[ "$CURRENT_TREE" == "$EXPECTED_BASE_TREE" ]]; then
  PATCH_FILE="$(mktemp)"
  PAYLOAD_LINE="$(awk '/^__PATCH_PAYLOAD_BELOW__$/ {print NR+1; exit}' "$0")"
  tail -n "+$PAYLOAD_LINE" "$0" | base64 -d > "$PATCH_FILE"
  ACTUAL_SHA="$(sha256sum "$PATCH_FILE" | awk '{print $1}')"
  if [[ "$ACTUAL_SHA" != "$EXPECTED_PATCH_SHA" ]]; then
    echo "ERROR: embedded patch checksum mismatch: $ACTUAL_SHA"
    rm -f "$PATCH_FILE"
    exit 4
  fi
  git config user.name "Slumdog Builder"
  git config user.email "slumdog-builder@users.noreply.github.com"
  if ! git am --3way "$PATCH_FILE"; then
    git am --abort || true
    rm -f "$PATCH_FILE"
    echo "ERROR: patch application failed and was aborted."
    exit 5
  fi
  rm -f "$PATCH_FILE"
else
  echo "ERROR: unexpected main tree."
  echo "Current:  $CURRENT_TREE"
  echo "Expected base:   $EXPECTED_BASE_TREE"
  echo "Expected target: $EXPECTED_TARGET_TREE"
  echo "Do not reset; ask the agent to rebase the patch."
  exit 6
fi

INSTALLED_TREE="$(git rev-parse HEAD^{tree})"
if [[ "$INSTALLED_TREE" != "$EXPECTED_TARGET_TREE" ]]; then
  echo "ERROR: installed tree mismatch: $INSTALLED_TREE"
  exit 7
fi

echo "Installing and validating..."
python -m pip install -e '.[dev]' pyyaml
python -m pytest
python -m pyflakes src tests
python -m compileall -q src
python - <<'PY'
import yaml
with open('.github/workflows/daily.yml') as handle:
    data = yaml.safe_load(handle)
assert data['name'] == 'Slumdog Full Forebet Build'
print('Workflow YAML: valid')
PY

if [[ "${NO_PUSH:-0}" == "1" ]]; then
  echo "NO_PUSH=1: validation complete; skipping push and workflow dispatch."
  exit 0
fi

echo "Pushing validated full-build tree to main..."
git push origin main

echo "Dispatching full Forebet build for $TARGET_DATE..."
if ! command -v gh >/dev/null 2>&1; then
  echo "ERROR: push succeeded, but gh CLI is unavailable."
  echo "Run the workflow manually with target_date=$TARGET_DATE."
  exit 8
fi

gh workflow run daily.yml --ref main -f target_date="$TARGET_DATE"
sleep 5
echo "Latest workflow runs:"
gh run list --workflow daily.yml --limit 3

echo
 echo "DONE: code pushed and full build dispatched."
exit 0

